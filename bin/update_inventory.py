#!/usr/bin/env python3
"""
update_inventory.py — Regenerates skills/INVENTORY.md from SKILL.md frontmatter.

Usage:
    python3 tools/update_inventory.py
    python3 tools/update_inventory.py --skills-dir /path/to/skills
"""

import os
import re
import yaml
import argparse
from pathlib import Path
from datetime import datetime, timezone


def extract_frontmatter(skill_md_path: Path) -> dict:
    """Extract YAML frontmatter from a SKILL.md file."""
    content = skill_md_path.read_text(encoding="utf-8")
    match = re.match(r"^---\s*\n(.*?)\n---\s*(\n|$)", content, re.DOTALL)
    if not match:
        return {}
    try:
        return yaml.safe_load(match.group(1)) or {}
    except yaml.YAMLError:
        return {}


def build_inventory(skills_dir: Path) -> list[dict]:
    """Walk skills_dir and extract metadata from every SKILL.md."""
    inventory = []
    for skill_path in sorted(skills_dir.iterdir()):
        skill_md = skill_path / "SKILL.md"
        if not skill_path.is_dir() or not skill_md.exists():
            continue

        meta = extract_frontmatter(skill_md)
        if not meta.get("name"):
            print(f"  WARN: No frontmatter name in {skill_md} — skipping")
            continue

        has_refs = (skill_path / "references").is_dir()
        ref_count = len(list((skill_path / "references").glob("*.md"))) if has_refs else 0

        inventory.append({
            "name": meta.get("name", skill_path.name),
            "description": meta.get("description", ""),
            "auto_triggers": meta.get("auto_triggers", []),
            "related_skills": meta.get("related_skills", []),
            "references": ref_count,
            "path": str(skill_path.relative_to(skills_dir.parent)),
        })

    return inventory


def render_markdown(inventory: list[dict]) -> str:
    """Render the inventory as a structured Markdown file."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Skills Inventory",
        "",
        f"> Auto-generated by `tools/update_inventory.py` on {now}.",
        "> Do not edit manually — run `python3 tools/update_inventory.py` to regenerate.",
        "",
        f"**Total skills**: {len(inventory)}",
        "",
        "---",
        "",
    ]

    for skill in inventory:
        lines.append(f"## {skill['name']}")
        lines.append("")
        lines.append(f"**Path**: `{skill['path']}/SKILL.md`  ")
        lines.append(f"**Description**: {skill['description']}  ")

        if skill["auto_triggers"]:
            triggers = ", ".join(f"`{t}`" for t in skill["auto_triggers"])
            lines.append(f"**Auto Triggers**: {triggers}  ")

        if skill["related_skills"]:
            related = ", ".join(f"`{r}`" for r in skill["related_skills"])
            lines.append(f"**Related Skills**: {related}  ")

        if skill["references"] > 0:
            lines.append(f"**SRE Runbooks**: {skill['references']} in `references/`  ")

        lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Regenerate skills/INVENTORY.md")
    parser.add_argument(
        "--skills-dir",
        default=None,
        help="Path to skills directory (default: auto-detected from script location)",
    )
    args = parser.parse_args()

    script_dir = Path(__file__).resolve().parent
    repo_root = script_dir.parent
    skills_dir = Path(args.skills_dir) if args.skills_dir else repo_root / "skills"

    if not skills_dir.exists():
        print(f"ERROR: Skills directory not found: {skills_dir}")
        exit(1)

    print(f"Scanning: {skills_dir}")
    inventory = build_inventory(skills_dir)
    print(f"Found {len(inventory)} skills")

    output_path = skills_dir / "INVENTORY.md"
    output_path.write_text(render_markdown(inventory), encoding="utf-8")
    print(f"Written: {output_path}")


if __name__ == "__main__":
    main()
